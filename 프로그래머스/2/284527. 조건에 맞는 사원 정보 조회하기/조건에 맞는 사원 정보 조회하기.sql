SELECT SUM(SCORE), E.EMP_NO, EMP_NAME, POSITION, EMAIL
FROM HR_EMPLOYEES AS E LEFT JOIN HR_GRADE AS G ON E.EMP_NO = G.EMP_NO
WHERE YEAR = 2022
GROUP BY G.EMP_NO
HAVING SUM(SCORE) >= ALL (SELECT SUM(SCORE)
                     FROM HR_EMPLOYEES AS E LEFT JOIN HR_GRADE AS G ON E.EMP_NO = G.EMP_NO
WHERE YEAR = 2022
GROUP BY G.EMP_NO)