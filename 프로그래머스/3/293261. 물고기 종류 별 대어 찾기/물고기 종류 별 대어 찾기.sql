SELECT ID, FISH_NAME, LENGTH
FROM FISH_NAME_INFO AS N LEFT JOIN FISH_INFO AS I ON N.FISH_TYPE = I.FISH_TYPE
WHERE (I.FISH_TYPE, LENGTH) IN (SELECT FISH_TYPE, MAX(LENGTH)
                                    FROM FISH_INFO
                                    GROUP BY FISH_TYPE)
ORDER BY ID ASC